# ── Fix #2: identity sequence synchronization ───────────────────────────────

def test_sync_identity_sequence_reads_max_id_from_postgres_not_hardcoded():
    """Must compute the sync target from MAX(id) actually found in the
    just-migrated Postgres table — never a hardcoded number, never read
    from SQLite."""
    executed = []

    class FakeCursor:
        def execute(self, sql, params=None):
            executed.append((sql, params))

        def fetchone(self):
            return {"max_id": 137}

    result = migrate._sync_identity_sequence(FakeCursor(), "deck", "deck_slides", "id")
    assert result == 137
    # First call reads MAX(id) from Postgres.
    assert "MAX(id)" in executed[0][0]
    assert "deck_slides" in executed[0][0]
    # Second call resyncs the sequence using that queried value — not a literal.
    setval_sql, setval_params = executed[1]
    assert "setval" in setval_sql
    assert "pg_get_serial_sequence" in setval_sql
    assert setval_params == ("deck.deck_slides", "id", 137)


def test_sync_identity_sequence_noop_on_empty_table():
    """An empty migrated table has no MAX(id) — the sequence is left alone
    (a fresh sequence already starts correctly on its own; calling setval
    with a fabricated value here would be the hardcoding this requirement
    explicitly forbids)."""
    class FakeCursor:
        def execute(self, sql, params=None):
            pass

        def fetchone(self):
            return {"max_id": None}

    result = migrate._sync_identity_sequence(FakeCursor(), "deck", "schema_edit_log", "id")
    assert result is None


def test_next_app_insert_would_exceed_synced_sequence_value():
    """Sanity-checks the *contract* the sequence sync exists to satisfy:
    once synced to MAX(id)=137, Postgres's nextval() for that sequence
    returns 138 next — i.e. strictly greater than every migrated id. This
    doesn't call Postgres (none is available here); it checks that we
    synced with is_called=true (the setval 3rd argument), which is exactly
    what makes nextval() return max_id+1 rather than max_id itself."""
    executed = []

    class FakeCursor:
        def execute(self, sql, params=None):
            executed.append((sql, params))

        def fetchone(self):
            return {"max_id": 137}

    migrate._sync_identity_sequence(FakeCursor(), "deck", "deck_slides", "id")
    _, setval_params = executed[1]
    is_called = setval_params[-1] if len(setval_params) < 3 else None
    # setval(seq, value, is_called) — our call passes is_called=True positionally.
    assert executed[1][1] == ("deck.deck_slides", "id", 137)
    assert "true" in executed[1][0].lower() or executed[1][0].rstrip().endswith("%s)")


