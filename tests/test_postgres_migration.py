# ── Fix #5: PostgreSQL transaction recovery on a cached connection ─────────

class _FakeConn:
    def __init__(self):
        self.rolled_back = False
        self.committed = False
        self.cursor_calls = 0

    def cursor(self):
        self.cursor_calls += 1
        return MagicMock()

    def rollback(self):
        self.rolled_back = True

    def commit(self):
        self.committed = True


class _FakePool:
    def __init__(self, conns):
        self._conns = list(conns)
        self.checked_out = []
        self.returned = []

    def getconn(self, timeout=None):
        conn = self._conns.pop(0)
        self.checked_out.append(conn)
        return conn

    def putconn(self, conn):
        self.returned.append(conn)


def test_failed_execute_rolls_back_and_releases_connection():
    """If a statement fails on a held connection, PgConnCompat must roll it
    back and return it to the pool immediately — never leave it cached in
    Postgres's aborted-transaction state for whatever the next unrelated
    call on this thread happens to be."""
    conn = _FakeConn()
    pool = _FakePool([conn])
    compat = PgConnCompat(pool, "session_store")

    # _checkout()'s "SET search_path" uses conn.cursor() as a context
    # manager, so its .execute() runs on the __enter__() mock, a separate
    # object from ok_cursor itself. The real query uses conn.cursor()
    # directly (no `with`), i.e. ok_cursor.execute() — fail only that one.
    ok_cursor = MagicMock()
    ok_cursor.execute.side_effect = RuntimeError("simulated statement failure")
    conn.cursor = lambda: ok_cursor

    try:
        compat.execute("SELECT * FROM sessions WHERE session_id=?", ("x",))
        raised = False
    except RuntimeError:
        raised = True

    assert raised, "the simulated failure should propagate to the caller"
    assert conn.rolled_back, "connection must be rolled back after a failed statement"
    assert conn in pool.returned, "connection must be returned to the pool, not leaked"
    assert compat._held_conn is None, "no connection should remain pinned after a failure"


# ── Write-batch atomicity preserved (hold-until-commit for non-SELECT) ─────

def test_writes_share_one_connection_until_commit_then_release():
    conn = _FakeConn()
    pool = _FakePool([conn])
    compat = PgConnCompat(pool, "deck")

    compat.execute("INSERT INTO deck_coverage_results (a) VALUES (?)", (1,))
    compat.execute("INSERT INTO deck_coverage_results (a) VALUES (?)", (2,))
    assert len(pool.checked_out) == 1, "a batch of writes before commit() must reuse one connection"
    assert conn not in pool.returned, "must not be released back to the pool before commit()"

    compat.commit()
    assert conn.committed
    assert conn in pool.returned, "must be released back to the pool once committed"
    assert compat._held_conn is None


def test_select_releases_connection_immediately_not_held_for_commit():
    conn = _FakeConn()
    pool = _FakePool([conn])
    compat = PgConnCompat(pool, "session_store")

    compat.execute("SELECT * FROM sessions WHERE session_id=?", ("x",))
    assert conn in pool.returned, "a read-only SELECT should release its connection right away"
    assert compat._held_conn is None

    # commit() with nothing pending must be a safe no-op (many read-only
    # call sites in the 7 modules never call commit() at all; some might).
    compat.commit()  # should not raise, should not check out a new connection
    assert len(pool.checked_out) == 1


